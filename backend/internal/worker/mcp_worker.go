package worker

import (
	"context"
	"errors"
	"log"
	"sync"

	"github.com/dika/contextkit/backend/internal/domain"
)

var (
	errQueueFull   = errors.New("mcp embedding queue is full, task dropped")
	errWorkerClosed = errors.New("mcp embedding worker is closed")
)

// memoryEmbeddingUpdater persists an asynchronously generated embedding. It is
// satisfied by repository.MCPMemoryRepository.
type memoryEmbeddingUpdater interface {
	UpdateEmbedding(ctx context.Context, memoryID string, embedding []float32) error
}

// MCPMemoryEmbedTask describes a memory whose embedding still needs to be
// generated by the embedding worker pool.
type MCPMemoryEmbedTask struct {
	ProjectID string
	MemoryID  string
	Content   string
}

// MCPEmbeddingWorker is a buffered channel worker pool that asynchronously
// generates pgvector embeddings for newly added memories. It mirrors the async
// embedding pattern used by the main backend (5 workers, 5000 task buffer).
type MCPEmbeddingWorker struct {
	queue      chan MCPMemoryEmbedTask
	client     domain.OpenRouterServiceClient
	memoryRepo memoryEmbeddingUpdater
	wg         sync.WaitGroup
	closeOnce  sync.Once
	closed     chan struct{}
}

// NewMCPEmbeddingWorker creates a worker pool with the given task buffer depth.
func NewMCPEmbeddingWorker(client domain.OpenRouterServiceClient, memoryRepo memoryEmbeddingUpdater, buffer int) *MCPEmbeddingWorker {
	if buffer <= 0 {
		buffer = 5000
	}
	return &MCPEmbeddingWorker{
		queue:      make(chan MCPMemoryEmbedTask, buffer),
		client:     client,
		memoryRepo: memoryRepo,
		closed:     make(chan struct{}),
	}
}

// Enqueue adds a task to the queue. It is non-blocking; if the queue is full
// the task is dropped and an error returned so the caller can log the loss.
func (w *MCPEmbeddingWorker) Enqueue(task MCPMemoryEmbedTask) error {
	select {
	case w.queue <- task:
		return nil
	case <-w.closed:
		return errWorkerClosed
	default:
		return errQueueFull
	}
}

// Start spins up n workers reading from the task queue.
func (w *MCPEmbeddingWorker) Start(n int) {
	if n <= 0 {
		n = 5
	}
	for i := 0; i < n; i++ {
		w.wg.Add(1)
		go w.run()
	}
}

// Close stops accepting new tasks and waits for in-flight workers to drain.
func (w *MCPEmbeddingWorker) Close() {
	w.closeOnce.Do(func() {
		close(w.closed)
		close(w.queue)
	})
	w.wg.Wait()
}

func (w *MCPEmbeddingWorker) run() {
	defer w.wg.Done()
	for task := range w.queue {
		w.process(task)
	}
}

func (w *MCPEmbeddingWorker) process(task MCPMemoryEmbedTask) {
	ctx := context.Background()

	embedding, err := w.client.GenerateEmbedding(ctx, task.Content)
	if err != nil {
		log.Printf("[MCP Embedding Worker Error]: failed to embed memory %s: %v", task.MemoryID, err)
		return
	}

	if err := w.memoryRepo.UpdateEmbedding(ctx, task.MemoryID, embedding); err != nil {
		log.Printf("[MCP Embedding Worker Error]: failed to persist embedding for memory %s: %v", task.MemoryID, err)
		return
	}
	log.Printf("[MCP Embedding Worker]: persisted embedding for memory %s", task.MemoryID)
}