def post_message(room_id, role, content):
    url = f"{BASE_URL}/v1/rooms/{room_id}/messages"
    data = {"role": role, "content": content}
    resp = requests.post(url, headers=headers, json=data)
    resp.raise_for_status()
    return resp.json()

def get_context(room_id, query, strategy="auto", max_tokens=4000):
    url = f"{BASE_URL}/v1/rooms/{room_id}/context"
    data = {
        "query": query,
        "policy": {
            "strategy": strategy,
            "max_tokens": max_tokens
        }
    }
    resp = requests.post(url, headers=headers, json=data)
    resp.raise_for_status()
    return resp.json()


