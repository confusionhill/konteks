@app.route("/api/rooms/new", methods=["POST"])
def create_room():
    try:
        data = request.json or {}
        external_user_id = data.get("external_user_id", f"user_{int(time.time())}")
        
        # Call Konteks Create Room API
        res = requests.post(f"{BASE_URL}/v1/rooms", headers=headers, json={"external_user_id": external_user_id})
        res.raise_for_status()
        room = res.json()
        return jsonify(room), 201
    except Exception as e:
        return jsonify({"error": str(e)}), 500

@app.route("/api/rooms/<room_id>/state", methods=["GET"])
def get_room_state(room_id):
    try:
        # 1. Fetch Room State from Konteks
        res = requests.get(f"{BASE_URL}/v1/rooms/{room_id}", headers=headers)
        res.raise_for_status()
        room_state = res.json()
        
        # 2. Fetch Message History
        res_msgs = requests.get(f"{BASE_URL}/v1/rooms/{room_id}/messages?limit=50", headers=headers)
        res_msgs.raise_for_status()
        messages_data = res_msgs.json()
        
        # 3. Fetch current Context Package
        context_pkg = {}
        try:
            start_time = time.time()
            context_pkg = get_context(room_id, "")
            duration_ms = (time.time() - start_time) * 1000
            print(f"   ⏱️ Context Retrieval Time (State Fetch): {duration_ms:.2f} ms")
        except Exception as ce:
            print(f"Failed to fetch context for room state {room_id}: {ce}")
            
        return jsonify({
            "room_state": room_state,
            "messages": messages_data.get("messages", []),
            "context": context_pkg
        })
    except Exception as e:
        return jsonify({"error": str(e)}), 500

@app.route("/api/chat", methods=["POST"])
def chat_turn():
    try:
        data = request.json or {}
        room_id = data.get("room_id")
        user_message = data.get("message")
        strategy = data.get("strategy", "auto")
        max_tokens = int(data.get("max_tokens", 4000))
        
        if not room_id or not user_message:
            return jsonify({"error": "Missing 'room_id' or 'message' parameters"}), 400
            
        # Store in thread context flask.g
        g.active_room_id = room_id
        global global_active_room_id
        global_active_room_id = room_id
        
        print("\n" + "="*80)
        print(f"📥 [Incoming Chat Message] Room: {room_id}")
        print(f"   User Message: \"{user_message}\"")
        print(f"   Policy: strategy='{strategy}', max_tokens={max_tokens}")
        print("="*80)
        
        # A. Post user message to Konteks
        print(f"\n[Step 1] Posting User Message to Konteks database...")
        post_message(room_id, "user", user_message)
        print("   ✅ User message successfully logged.")
        
        # B. Retrieve compiled context package from Konteks
        print(f"\n[Step 2] Retrieving Compiled Context Package from Konteks...")
        start_time = time.time()
        context_package = get_context(room_id, user_message, strategy=strategy, max_tokens=max_tokens)
        duration_ms = (time.time() - start_time) * 1000
        
        state_str = json.dumps(context_package.get('state', {}))
        memories = context_package.get('memories') or []
        memories_str = ", ".join([f'"{m.get("content", "")}"' for m in memories])
        
        print(f"   ⏱️ Context Retrieval Time: {duration_ms:.2f} ms")
        print(f"   🧠 Konteks Context Compiled:")
        print(f"      - Active Topic: {context_package.get('active_topic')}")
        print(f"      - Summary     : {context_package.get('summary')}")
        print(f"      - State variables: {state_str}")
        print(f"      - User memories: [{memories_str}]")
        print(f"      - Messages history fetched: {len(context_package.get('relevant_messages', []))} turns")
        
        # C. Rebuild LangChain system prompt dynamically with retrieved context variables
        print(f"\n[Step 3] Rebuilding LangChain Agent Prompt dynamically using Konteks values...")
        system_prompt = f"""You are a helpful travel assistant.
Use the following context package parameters from context-as-a-service layer to guide your tool selections and decisions:
- Conversation Summary: {context_package.get('summary', '')}
- Active Topic: {context_package.get('active_topic', '')}
- Current State Variables: {state_str}
- User Long-term Memories: [{memories_str}]

Rules:
1. Always resolve relative references (like "it", "same as my other trip", "that hotel") using the parameters above.
2. If the user asks to book "it", book the hotel/flight/activity option that was just output, discussed, or recorded in state.
3. Be friendly and keep responses relatively concise.
""".replace("{", "{{").replace("}", "}}")
        
        prompt = ChatPromptTemplate.from_messages([
            ("system", system_prompt),
            MessagesPlaceholder("chat_history"),
            ("human", "{input}"),
            MessagesPlaceholder("agent_scratchpad")
        ])
        
        # Initialize LangChain model pointing to OpenRouter
        llm = ChatOpenAI(
            model=cfg.get("openrouter_chat_model", "google/gemini-2.5-flash"),
            openai_api_key=api_key,
            openai_api_base=cfg.get("openrouter_base_url", "https://openrouter.ai/api/v1")
        )
        
        # Create tool calling agent
        agent = create_tool_calling_agent(llm, tools_list, prompt)
        # Enable returning intermediate steps to capture tool logs
        agent_executor = AgentExecutor(agent=agent, tools=tools_list, verbose=True, return_intermediate_steps=True)
        
        # Build chat history object for the LLM using retrieved relevant messages
        llm_history = []
        for msg in context_package.get('relevant_messages', []):
            role = msg.get('role')
            content = msg.get('content')
            if role == 'user':
                llm_history.append(HumanMessage(content=content))
            elif role == 'assistant':
                llm_history.append(AIMessage(content=content))
                
        # D. Execute LangChain Agent completion
        print(f"\n[Step 4] Starting LangChain Agent loop...")
        response = agent_executor.invoke({
            "input": user_message,
            "chat_history": llm_history
        })
        assistant_output = response["output"]
        intermediate_steps = response.get("intermediate_steps", [])
        print(f"   🤖 Agent completed planning.")
        print(f"      - Final response: \"{assistant_output}\"")
        
        # E. Post Assistant response to Konteks
        print(f"\n[Step 5] Saving Assistant response back to Konteks...")
        post_message(room_id, "assistant", assistant_output)
        print("   ✅ Assistant response successfully logged.")
        
        # Serialize intermediate steps (tool calls) to return to frontend
        tool_calls_log = []
        for action, observation in intermediate_steps:
            tool_input = action.tool_input
            if isinstance(tool_input, str):
                try:
                    tool_input = json.loads(tool_input)
                except Exception:
                    pass
            tool_calls_log.append({
                "tool": action.tool,
                "input": tool_input,
                "output": observation
            })
            
        # Get final state after assistant response
        updated_context = get_context(room_id, "")
        
        print(f"\n[Step 6] Completed turn. Sending response to UI.")
        print(f"   - Tool calls executed: {len(tool_calls_log)}")
        print("="*80 + "\n")
        
        return jsonify({
            "response": assistant_output,
            "tool_calls": tool_calls_log,
            "context": updated_context
        })
        
    except Exception as e:
        print(f"Error handling chat turn: {e}")
        return jsonify({"error": str(e)}), 500

