@tool
def book_hotel(hotel_name: str, check_in_date: str, nights: int) -> str:
    """Book a hotel by its name, check-in date, and number of nights."""
    room_id = get_active_room_id()
    print(f"\n>>> [Tool Triggered]: book_hotel(hotel_name='{hotel_name}', date='{check_in_date}', nights={nights})")
    
    log_event(room_id, "tool.started", {
        "tool_name": "book_hotel",
        "args": {"hotel_name": hotel_name, "check_in_date": check_in_date, "nights": nights}
    })
    
    booking_id = f"HTL-{time.strftime('%Y%m%d')}-{abs(hash(hotel_name)) % 10000:04d}"
    output = {
        "status": "confirmed",
        "booking_id": booking_id,
        "hotel": hotel_name,
        "check_in": check_in_date,
        "nights": nights,
        "message": f"Successfully booked {hotel_name} for {nights} nights starting {check_in_date}."
    }
    result = json.dumps(output)
    print(f"<<< [Tool Output]: {result}")
    
    log_event(room_id, "tool.completed", {
        "tool_name": "book_hotel",
        "output": output
    })
    return result

