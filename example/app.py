# Global fallback active room ID (primarily for standalone testing)
global_active_room_id = ""

def get_active_room_id():
    """Retrieve the room ID associated with the current thread or Flask request."""
    try:
        from flask import has_request_context
        if has_request_context():
            return g.get("active_room_id", "")
    except Exception:
        pass
    return global_active_room_id

def log_event(room_id, event_type, payload):
    if not room_id:
        return
    url = f"{BASE_URL}/v1/rooms/{room_id}/events"
    data = {
        "type": event_type,
        "payload": payload
    }
    try:
        requests.post(url, headers=headers, json=data)
    except Exception as e:
        print(f"  [Event Log Error]: {e}")

